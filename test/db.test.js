const test = require('node:test')
const assert = require('node:assert')
const fs = require('fs')
const os = require('os')
const path = require('path')
const banco = require('../db')

test('migra o vinculos.json da v0.1 uma única vez e preserva as credenciais', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'mig-'))
  fs.writeFileSync(path.join(dir, 'vinculos.json'), JSON.stringify({ computadores: { pc1: { hash: 'h1', criado: 1 } }, celulares: { cel1: { computadorId: 'pc1', hash: 'h2', nome: 'iPhone · Safari', criado: 2 }, orfao: { computadorId: 'nao-existe', hash: 'x', nome: 'x', criado: 3 } } }))
  const db = banco.abrir(dir)
  assert.equal(db.migrarJson(path.join(dir, 'vinculos.json')), 1)
  assert.equal(db.computador('pc1').hash, 'h1')
  assert.equal(db.celular('cel1').nome, 'iPhone · Safari')
  assert.equal(db.celular('orfao'), undefined)
  assert.ok(fs.existsSync(path.join(dir, 'vinculos.json.migrado')))
  assert.equal(db.migrarJson(path.join(dir, 'vinculos.json')), 0)
  db.fechar()
})

test('apagar o computador apaga celulares, códigos e arquivos (cascata)', () => {
  const db = banco.abrir(fs.mkdtempSync(path.join(os.tmpdir(), 'cas-')))
  db.computadorNovo('pc', 'h')
  db.celularNovo('c', 'pc', 'h', 'x')
  db.codigoNovo('cod', 'pc', Date.now() + 1000)
  db.arquivoNovo({ id: 'a', computadorId: 'pc', celularId: 'c', nome: 'n', tipo: 't', tamanho: 1 })
  db.raw.prepare('DELETE FROM computadores WHERE id = ?').run('pc')
  assert.equal(db.celular('c'), undefined)
  assert.equal(db.arquivo('a'), undefined)
  assert.equal(db.codigoConsumir('cod'), null)
  db.fechar()
})
